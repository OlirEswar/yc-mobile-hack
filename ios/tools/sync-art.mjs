#!/usr/bin/env node
/**
 * Keeps the iOS app's art and map geometry in lockstep with the shared sources:
 *   mobile/shared/mapLayout.ts      footprints, doors, stand areas, route waypoints
 *   mobile/assets/game/manifest.ts  building origins, character atlas, portraits, icons, fx
 * It copies every PNG the manifest references into ios/LivingMoon/Art (flat, since the bundle is
 * flat), removes PNGs the manifest no longer references, and writes ios/LivingMoon/ArtLayout.swift.
 *
 * Run from anywhere: `node ios/tools/sync-art.mjs` (Node 22.6+ for TypeScript type stripping).
 */
import { copyFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const gameDir = join(repo, 'mobile/assets/game');
const artDir = join(repo, 'ios/LivingMoon/Art');
const swiftOut = join(repo, 'ios/LivingMoon/ArtLayout.swift');

// manifest.ts calls require('./x.png') for each image; record the relative path instead.
globalThis.require = (path) => path;
const { MANIFEST, ART_SCALE = 1 } = await import(pathToFileURL(join(gameDir, 'manifest.ts')).href);
const { LOCATION_LAYOUT, ROUTE_WAYPOINTS, MAP_WIDTH, MAP_HEIGHT } = await import(pathToFileURL(join(repo, 'mobile/shared/mapLayout.ts')).href);

const copied = new Set();
/** Copies one manifest image into Art/ and returns its bundle name (the file name without .png). */
function asset(image) {
  const file = basename(image.source);
  if (!copied.has(file)) copyFileSync(join(gameDir, image.source), join(artDir, file));
  copied.add(file);
  return file.replace(/\.png$/, '');
}

const n = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2));
const point = (p) => `CGPoint(x: ${n(p.x)}, y: ${n(p.y)})`;
const rect = (r) => `CGRect(x: ${n(r.x)}, y: ${n(r.y)}, width: ${n(r.w)}, height: ${n(r.h)})`;
const str = (s) => (s === undefined ? 'nil' : `"${s}"`);
const dict = (entries) => (entries.length ? `[\n${entries.map((e) => `        ${e},`).join('\n')}\n    ]` : '[:]');

const locations = Object.entries(LOCATION_LAYOUT).map(
  ([id, l]) => `.${id}: LocationLayout(center: ${point(l.center)}, footprint: ${rect(l.footprint)}, entry: ${point(l.entry)}, standAreas: [${l.standAreas.map(rect).join(', ')}])`,
);
const waypoints = Object.entries(ROUTE_WAYPOINTS).map(([key, pts]) => `"${key}": [${pts.map(point).join(', ')}]`);
const buildings = Object.entries(MANIFEST.buildings).map(
  ([id, b]) =>
    `.${id}: BuildingArt(origin: CGPoint(x: ${n(b.x)}, y: ${n(b.y)}), size: CGSize(width: ${n(b.base.width / ART_SCALE)}, height: ${n(b.base.height / ART_SCALE)}), base: ${str(asset(b.base))}, overlay: ${str(b.overlay && asset(b.overlay))}, damaged: ${str(b.damaged && asset(b.damaged))})`,
);
const chars = MANIFEST.characters;
const rows = Object.entries(chars.rows).map(([sprite, row]) => `"${sprite}": ${row}`);
const portraits = Object.entries(MANIFEST.portraits).map(([sprite, image]) => `"${sprite}": "${asset(image)}"`);
const powers = Object.entries(MANIFEST.icons.powers).map(([power, image]) => `"${power}": "${asset(image)}"`);
const resources = Object.entries(MANIFEST.icons.resources).map(([res, image]) => `"${res}": "${asset(image)}"`);
const fx = MANIFEST.fx;

const swift = `// Generated by ios/tools/sync-art.mjs from mobile/shared/mapLayout.ts and mobile/assets/game/manifest.ts.
// Do not edit by hand: change the shared sources, then run node ios/tools/sync-art.mjs.
import CoreGraphics

struct LocationLayout {
    /// Visual centre, also where the name label sits.
    let center: CGPoint
    /// Bounding box of the building art. Tapping inside selects the location.
    let footprint: CGRect
    /// Door: where routes attach and where colonists enter and leave.
    let entry: CGPoint
    /// Open floor where colonists stand, work and idle.
    let standAreas: [CGRect]
}

struct BuildingArt {
    /// World px of the top-left corner of every layer.
    let origin: CGPoint
    let size: CGSize
    /// Floor and walls, drawn under the colonists.
    let base: String
    /// Dome glass and roof rims, drawn over the colonists.
    let overlay: String?
    /// Drawn over the base while the location is damaged.
    let damaged: String?
}

enum MapLayout {
    static let size = CGSize(width: ${MAP_WIDTH}, height: ${MAP_HEIGHT})
    /// Art pixels per world pixel in the ground, building, character and fx images.
    static let artScale: CGFloat = ${ART_SCALE}
    static let ground = "${asset(MANIFEST.map.ground)}"

    static let locations: [LocationId: LocationLayout] = ${dict(locations)}

    /// Intermediate points keyed by routeKey(a, b), listed from the alphabetically smaller id to the larger.
    static let routeWaypoints: [String: [CGPoint]] = ${dict(waypoints)}

    static let buildings: [LocationId: BuildingArt] = ${dict(buildings)}
}

/// The character atlas: one row per sprite; columns are direction * framesPerDirection + frame, with
/// directions down, left, right, up. Frame 0 of each direction is the standing pose.
enum CharacterArt {
    static let atlas = "${asset(chars.atlas)}"
    /// One frame in world px; in the atlas it is artScale times larger.
    static let frame = CGSize(width: ${n(chars.frameWidth / ART_SCALE)}, height: ${n(chars.frameHeight / ART_SCALE)})
    /// The point between the feet inside a frame, in world px; it sits on the colonist's world position.
    static let feet = CGPoint(x: ${n(chars.feet.x / ART_SCALE)}, y: ${n(chars.feet.y / ART_SCALE)})
    static let framesPerDirection = ${chars.framesPerDirection}
    static let rows: [String: Int] = ${dict(rows)}
}

enum IconArt {
    static let portraits: [String: String] = ${dict(portraits)}
    static let powers: [String: String] = ${dict(powers)}
    static let resources: [String: String] = ${dict(resources)}
    static let grave = "${asset(fx.grave)}"
    static let selection = "${asset(fx.selection)}"
    static let stormOverlay: String? = ${str(fx.stormOverlay && asset(fx.stormOverlay))}
    static let droughtOverlay: String? = ${str(fx.droughtOverlay && asset(fx.droughtOverlay))}
}
`;

writeFileSync(swiftOut, swift);
// Hand-made UI art that lives in Art/ but not in the manifest.
const KEEP = new Set(['onboarding_moon.png']);
const stale = readdirSync(artDir).filter((f) => f.endsWith('.png') && !copied.has(f) && !KEEP.has(f));
for (const f of stale) rmSync(join(artDir, f));
console.log(`ArtLayout.swift written; ${copied.size} images copied, ${stale.length} stale removed.`);
