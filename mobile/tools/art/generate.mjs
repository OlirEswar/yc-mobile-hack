/**
 * Generates every piece of game art into mobile/assets/game/ and writes manifest.ts there.
 * Deterministic and dependency-free (plain node 22+):
 *   node mobile/tools/art/generate.mjs [ground] [buildings] [characters] [icons]
 * With no arguments every part is drawn. The manifest is always rewritten from the files present.
 * Then `node mobile/tools/art/preview.mjs` composites the previews in mobile/tools/art/previews/.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePng, encodePng } from './lib/image.mjs';
import { quantize } from './lib/palette.mjs';
import { ART_SCALE, LOCATION_IDS, LOCATION_LAYOUT, MAP_HEIGHT, MAP_WIDTH, RESOURCES, SPRITE_ARCHETYPES, SPRITE_VARIANTS } from './lib/layout.mjs';
import { paintGround } from './ground.mjs';
import { paintBuilding } from './buildings/index.mjs';
import { FEET, FRAMES, FRAME_H, FRAME_W, paintCharacters } from './characters.mjs';
import { paintDroughtOverlay, paintGrave, paintPowerIcons, paintResourceIcons, paintSelection, paintStormOverlay } from './icons.mjs';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../assets/game');
const ALL = ['ground', 'buildings', 'characters', 'icons'];
const parts = new Set(process.argv.length > 2 ? process.argv.slice(2) : ALL);
const POWERS = ['drought', 'storm', 'grant', 'kill', 'whisper', 'rumor', 'create_character'];

function save(name, img) {
  const file = join(OUT, name);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, encodePng(quantize(img)));
}

if (parts.has('ground')) save('ground.png', paintGround());
if (parts.has('buildings'))
  LOCATION_IDS.forEach((id, i) => {
    const b = paintBuilding(id, 100 + i);
    save('buildings/' + id + '_base.png', b.base);
    save('buildings/' + id + '_overlay.png', b.overlay);
    save('buildings/' + id + '_damaged.png', b.damaged);
  });
if (parts.has('characters')) {
  const { atlas, portraits } = paintCharacters();
  save('characters.png', atlas);
  for (const [id, img] of Object.entries(portraits)) save('portraits/' + id + '.png', img);
}
if (parts.has('icons')) {
  for (const [name, img] of Object.entries(paintPowerIcons())) save('icons/power_' + name + '.png', img);
  for (const [name, img] of Object.entries(paintResourceIcons())) save('icons/res_' + name + '.png', img);
  save('fx/grave.png', paintGrave());
  save('fx/selection.png', paintSelection());
  save('fx/storm_overlay.png', paintStormOverlay());
  save('fx/drought_overlay.png', paintDroughtOverlay());
}

// ---------- manifest ----------
const asset = (name) => {
  const img = decodePng(readFileSync(join(OUT, name)));
  return "{ source: require('./" + name + "'), width: " + img.w + ', height: ' + img.h + ' }';
};
const spriteIds = SPRITE_ARCHETYPES.flatMap((a) => Array.from({ length: SPRITE_VARIANTS }, (_, v) => a + '_' + v));
const lines = [
  '// Generated by mobile/tools/art/generate.mjs. Do not edit by hand.',
  "import type { AssetManifest } from '../../shared/assets';",
  '',
  '/** Art pixels per world pixel for the map, buildings, characters and fx (icons and portraits are UI art). */',
  'export const ART_SCALE = ' + ART_SCALE + ';',
  '',
  'export const MANIFEST: AssetManifest = {',
  '  map: { width: ' + MAP_WIDTH + ', height: ' + MAP_HEIGHT + ", ground: " + asset('ground.png') + ' },',
  '  buildings: {',
  ...LOCATION_IDS.map((id) => {
    const f = LOCATION_LAYOUT[id].footprint;
    const p = 'buildings/' + id;
    return '    ' + id + ': { x: ' + f.x + ', y: ' + f.y + ', base: ' + asset(p + '_base.png') + ', overlay: ' + asset(p + '_overlay.png') + ', damaged: ' + asset(p + '_damaged.png') + ' },';
  }),
  '  },',
  '  characters: {',
  '    atlas: ' + asset('characters.png') + ',',
  '    frameWidth: ' + FRAME_W + ',',
  '    frameHeight: ' + FRAME_H + ',',
  '    framesPerDirection: ' + FRAMES + ',',
  '    rows: {',
  ...spriteIds.map((id, row) => '      ' + id + ': ' + row + ','),
  '    },',
  '    feet: { x: ' + FEET.x + ', y: ' + FEET.y + ' },',
  '  },',
  '  portraits: {',
  ...spriteIds.map((id) => '    ' + id + ': ' + asset('portraits/' + id + '.png') + ','),
  '  },',
  '  icons: {',
  '    powers: {',
  ...POWERS.map((p) => '      ' + p + ': ' + asset('icons/power_' + p + '.png') + ','),
  '    },',
  '    resources: {',
  ...RESOURCES.map((r) => '      ' + r + ': ' + asset('icons/res_' + r + '.png') + ','),
  '    },',
  '  },',
  '  fx: {',
  '    grave: ' + asset('fx/grave.png') + ',',
  '    selection: ' + asset('fx/selection.png') + ',',
  '    stormOverlay: ' + asset('fx/storm_overlay.png') + ',',
  '    droughtOverlay: ' + asset('fx/drought_overlay.png') + ',',
  '  },',
  '};',
];
writeFileSync(join(OUT, 'manifest.ts'), lines.join('\n') + '\n');
console.log('art written to', OUT, '(' + [...parts].join(', ') + ')');
